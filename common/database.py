def is_userbot_inline_disabled(chat_id: int) -> bool:
    """Yoxlayır: göstərilən çatda userbot inline kartları söndürülübmü."""
    try:
        val = get_setting(f"ub_no_inline:{chat_id}")
        if val is not None:
            return val == "1"
    except Exception as _e:
        logger.debug("udulan xəta [common/database.py:1487]: %r", _e)
    try:
        from userbot.core.userbot_db import get_udb
        udb = get_udb()
        if udb:
            return bool(udb.kv_get("inline_disabled", str(chat_id), False))
    except Exception as _e:
        logger.debug("udulan xəta [common/database.py:1494]: %r", _e)
    return False


def set_userbot_inline_disabled(chat_id: int, disabled: bool) -> bool:
    """Göstərilən çat üçün userbot inline rejimini söndürür (True) və ya açır (False)."""
    val = "1" if disabled else "0"
    set_setting(f"ub_no_inline:{chat_id}", val)
    try:
        from userbot.core.userbot_db import get_udb
        udb = get_udb()
        if udb:
            if disabled:
                udb.kv_set("inline_disabled", str(chat_id), True)
            else:
                udb.kv_del("inline_disabled", str(chat_id))
    except Exception as _e:
        logger.debug("udulan xəta [common/database.py:1511]: %r", _e)
    return disabled


def get_userbot_inline_disabled_chats() -> list[int]:
    """İnline rejimi söndürülmüş bütün çatların ID siyahısını qaytarır."""
    chats = set()
    try:
        db = get_db()
        if hasattr(db, "_settings"):
            for k, v in list(db._settings.items()):     # thread-lər eyni anda yaza bilər
                if k.startswith("ub_no_inline:") and v == "1":
                    with contextlib.suppress(ValueError):
                        chats.add(int(k.split(":", 1)[1]))
    except Exception as _e:
        logger.debug("udulan xəta [common/database.py:1526]: %r", _e)
    try:
        from userbot.core.userbot_db import get_udb
        udb = get_udb()
        if udb:
            all_kv = udb.kv_all("inline_disabled")
            for k, v in all_kv.items():
                if v:
                    with contextlib.suppress(ValueError):
                        chats.add(int(k))
    except Exception as _e:
        logger.debug("udulan xəta [common/database.py:1537]: %r", _e)
    return sorted(chats)


