    # ───────────── istifadəçi siyahısı: filtr + axtarış ─────────────
    _USER_FILTERS = {
        "all":     ("1=1", "u.first_seen DESC"),
        "active":  ("u.last_seen >= %(week)s AND u.blocked = 0", "u.last_seen DESC"),
        "new":     ("u.first_seen >= %(week)s", "u.first_seen DESC"),
        "top":     ("1=1", "dl_total DESC, u.last_seen DESC"),
        "prem":    ("p.user_id IS NOT NULL", "u.first_seen DESC"),
        "blocked": ("u.blocked = 1", "u.last_seen DESC"),
    }
    _USER_SELECT = """
        SELECT u.*, COALESCE(d.n, 0) AS dl_total, (p.user_id IS NOT NULL)::int AS premium
        FROM users u
        LEFT JOIN (SELECT user_id, COUNT(*) AS n FROM downloads GROUP BY user_id) d ON d.user_id = u.user_id
        LEFT JOIN premium p ON p.user_id = u.user_id AND (p.until IS NULL OR p.until > %(now)s)
    """

    def users_filtered(self, flt: str, offset: int, limit: int, now: int):
        """(sətirlər, cəmi say)"""
        where, order = self._USER_FILTERS.get(flt, self._USER_FILTERS["all"])
        params = {"now": now, "week": now - 7 * 86400, "limit": limit, "offset": offset}
        with self._conn() as c:
            total = c.execute(
                f"SELECT COUNT(*) AS n FROM ({self._USER_SELECT} WHERE {where}) AS t", params).fetchone()["n"]
            rows = c.execute(
                f"{self._USER_SELECT} WHERE {where} ORDER BY {order} LIMIT %(limit)s OFFSET %(offset)s",
                params).fetchall()
        return rows, total

    def filter_counts(self, now: int) -> dict:
        params = {"now": now, "week": now - 7 * 86400}
        out = {}
        with self._conn() as c:
            for key, (where, _) in self._USER_FILTERS.items():
                if key == "top":
                    continue
                out[key] = c.execute(
                    f"SELECT COUNT(*) AS n FROM ({self._USER_SELECT} WHERE {where}) AS t", params).fetchone()["n"]
        out["top"] = out["all"]
        return out

    def search_users(self, query: str, now: int, limit: int = 10) -> list:
        """ID (tam), @username və ya ad üzrə axtarış."""
        q = (query or "").strip().lstrip("@")
        if not q:
            return []
        params = {"now": now, "id": int(q) if q.isdigit() else -1, "like": f"%{q}%", "limit": limit}
        return self._all(
            f"""{self._USER_SELECT}
                WHERE u.user_id = %(id)s OR u.username ILIKE %(like)s
                   OR u.first_name ILIKE %(like)s OR u.last_name ILIKE %(like)s
                ORDER BY (u.user_id = %(id)s) DESC, dl_total DESC LIMIT %(limit)s""", params)

