    def cache_search(self, query: str, limit: int = 5) -> list:
        """PostgreSQL pg_trgm GIN indeksi ilə depoda ultra-sürətli axtarış."""
        q = re.sub(r'["\'«»“”„‟`]', ' ', query or '').strip()
        q = re.sub(r'\s+', ' ', q).strip(" -:;,.")
        if not q:
            return []
        if not getattr(self, "_trgm", True):
            return self._all(
                """SELECT video_id, file_id, unique_id, title, performer, duration, size,
                          chat_id, message_id, hits, 0.0 AS sm
                   FROM audio_cache
                   WHERE (COALESCE(performer, '') || ' ' || COALESCE(title, '')) ILIKE %s
                   ORDER BY hits DESC LIMIT %s""", (f"%{q}%", limit))
        sql = """
            SELECT video_id, file_id, unique_id, title, performer, duration, size,
                   chat_id, message_id, hits,
                   similarity(COALESCE(performer, '') || ' ' || COALESCE(title, ''), %s) AS sm
            FROM audio_cache
            WHERE (COALESCE(performer, '') || ' ' || COALESCE(title, '')) %% %s
               OR (COALESCE(performer, '') || ' ' || COALESCE(title, '')) ILIKE %s
            ORDER BY sm DESC, hits DESC
            LIMIT %s
        """
        return self._all(sql, (q, q, f"%{q}%", limit))

