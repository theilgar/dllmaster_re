HIDE_DURATION_STEPS = [0, 5, 10, 15, 20, 30, 45, 60, 90, 120]


def cycle_auto_hide_duration(direction: int = 1) -> int:
    """Növbəti müddət pilləsinə keçir (0, 5, 10, 15, 20, 30, 45, 60, 90, 120 san)."""
    cur = get_auto_hide_duration()
    steps = HIDE_DURATION_STEPS
    if cur in steps:
        idx = (steps.index(cur) + direction) % len(steps)
    else:
        idx = min(range(len(steps)), key=lambda i: abs(steps[i] - cur))
        idx = (idx + direction) % len(steps)
    new_val = steps[idx]
    set_auto_hide_duration(new_val)
    return new_val


def step_auto_hide_duration(delta: int = 5) -> int:
    """Müddəti delta saniyə artırır və ya azaldır (0-300 san arası)."""
    cur = get_auto_hide_duration()
    new_val = max(0, min(300, cur + delta))
    set_auto_hide_duration(new_val)
    return new_val


