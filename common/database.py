class Settings:
    """Bir prefiks altında baza ayarları — modulların öz _get / _set / _s / _put sarğıları əvəzinə.

        S = Settings("logs:")            S.get("interval", "0") · S.put("interval", 30)
        S.flag("on") / S.toggle("on")    "1" / "0" bayraqları
        S.int("rate", 10, lo=1, hi=60)   rəqəm (sərhəd və ya icazəli siyahı: allowed=[...])

    empty_is_default=True — boş sətir də "təyin olunmayıb" sayılır (UI-də sıfırlanan ayarlar üçün).
    Oxuma heç vaxt xəta atmır (baza hazır deyilsə — default); yazma bazanın özü kimi str() edir."""

    def __init__(self, prefix: str = "", empty_is_default: bool = False):
        self.prefix, self.empty = prefix, empty_is_default

    def get(self, key, default=None):
        v = get_setting(self.prefix + key)
        return default if v is None or (self.empty and v == "") else v

    def put(self, key, value):
        return set_setting(self.prefix + key, value)

    def flag(self, key, default: str = "0") -> bool:
        return self.get(key, default) == "1"

    def toggle(self, key, default: str = "0") -> bool:
        v = not self.flag(key, default)
        self.put(key, "1" if v else "0")
        return v

    def int(self, key, default: int, lo: int = None, hi: int = None, allowed=None) -> int:
        try:
            v = int(self.get(key, default))
        except (TypeError, ValueError):
            return default
        if allowed is not None:
            return v if v in allowed else default
        if lo is not None:
            v = max(lo, v)
        if hi is not None:
            v = min(hi, v)
        return v


